#include <iostream>

int main() {

    int a = 10;
    int b = 3;

    std::cout << "Add: " << a + b << std::endl;
    std::cout << "Sub: " << a - b << std::endl;
    std::cout << "Mul: " << a * b << std::endl;
    std::cout << "Div: " << a / b << std::endl;
    std::cout << "Mod: " << a % b << std::endl;

    return 0;
}